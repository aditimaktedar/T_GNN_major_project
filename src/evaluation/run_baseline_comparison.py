"""Generate baseline comparison report from saved checkpoints (inference-only)."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from src.data.config import METRICS_DIR, PROJECT_ROOT
from src.evaluation.baseline_comparison import (
    METRIC_KEYS,
    MODEL_SPECS,
    build_baseline_comparison,
    format_pct,
    format_relative,
)

OUTPUT_JSON = METRICS_DIR / "baseline_comparison.json"
OUTPUT_MD = PROJECT_ROOT / "docs" / "BASELINE_COMPARISON.md"


def _table_row(cells: list[str]) -> str:
    return "| " + " | ".join(cells) + " |"


def _metric_value(comparison: dict, split: str, slice_key: str, metric: str, model_key: str) -> float | None:
    return comparison["splits"][split][slice_key][model_key].get(metric)


def _executive_summary(comparison: dict) -> list[str]:
    primary_test = "test/seen_class/pair_type_dedup"
    freq_test = "test/frequent_ge_20/pair_type_dedup"
    top3 = comparison["best_by_metric"][f"{primary_test}/top_3_accuracy"]
    top5 = comparison["best_by_metric"][f"{primary_test}/top_5_accuracy"]
    macro = comparison["best_by_metric"][f"{primary_test}/macro_f1"]
    freq_top3 = comparison["best_by_metric"][f"{freq_test}/top_3_accuracy"]
    freq_top5 = comparison["best_by_metric"][f"{freq_test}/top_5_accuracy"]

    def names(keys: list[str]) -> str:
        return ", ".join(comparison["models"][k]["display_name"] for k in keys)

    lr_top3 = _metric_value(comparison, "test", "seen_class/pair_type_dedup", "top_3_accuracy", "logistic_regression")
    gnn_top3 = _metric_value(comparison, "test", "seen_class/pair_type_dedup", "top_3_accuracy", "molecular_gnn")
    gnn_freq_top3 = _metric_value(comparison, "test", "frequent_ge_20/pair_type_dedup", "top_3_accuracy", "molecular_gnn")

    return [
        "## Executive summary",
        "",
        f"- **Best test top-3 (seen_class / pair_type_dedup):** {names(top3['best_models'])} ({format_pct(top3['values'][top3['best_models'][0]])})",
        f"- **Best test top-5 (seen_class / pair_type_dedup):** {names(top5['best_models'])} ({format_pct(top5['values'][top5['best_models'][0]])})",
        f"- **Best test macro F1 (seen_class / pair_type_dedup):** {names(macro['best_models'])} ({format_pct(macro['values'][macro['best_models'][0]])})",
        f"- **Best test top-3 (frequent_ge_20 / pair_type_dedup):** {names(freq_top3['best_models'])} ({format_pct(freq_top3['values'][freq_top3['best_models'][0]])})",
        f"- **Best test top-5 (frequent_ge_20 / pair_type_dedup):** {names(freq_top5['best_models'])} ({format_pct(freq_top5['values'][freq_top5['best_models'][0]])})",
        "",
        "Molecular GNN vs Logistic Regression on primary test top-3 (seen_class): "
        f"{format_relative(_relative_delta(gnn_top3, lr_top3))} (not statistically tested). "
        "On the frequent-class test slice, Molecular GNN leads top-3/top-5 but absolute scores remain below 1.3%.",
        "",
        "**Overall:** Logistic Regression remains strongest on the primary seen-class test slice; "
        "Molecular GNN shows the largest gains on the frequent-class test slice. No model clearly dominates all metrics.",
        "",
        "---",
        "",
    ]


def _relative_delta(value: float | None, baseline: float | None) -> float | None:
    from src.evaluation.baseline_comparison import _relative_delta as rel

    return rel(value, baseline)


def render_markdown(comparison: dict) -> str:
    lines = [
        "# Baseline Comparison — Multiclass DDI Models",
        "",
        "Comparison of three completed baselines on `data/processed/final_mimic_twosides_ml.csv`.",
        "",
        "**No new training was performed.** Metrics are taken from saved checkpoints evaluated",
        "under `docs/EVALUATION_PROTOCOL.md`. Logistic Regression protocol metrics were",
        "generated by inference-only evaluation when no cached protocol file was present.",
        "",
        "---",
        "",
        *_executive_summary(comparison),
        "## 1. Models compared",
        "",
        _table_row(["Model", "Checkpoint", "Protocol source"]),
        _table_row(["---", "---", "---"]),
    ]
    for model_key, info in comparison["models"].items():
        source = "cached JSON" if info.get("protocol_from_cache") else "inference-only eval"
        lines.append(_table_row([info["display_name"], f"`{Path(info['checkpoint']).name}`", source]))
    lines.extend(
        [
            "",
            "## 2. Experiment parity",
            "",
            "| Check | Status |",
            "|---|---|",
            f"| Same dataset | {comparison['experiment_parity']['same_dataset']} |",
            f"| Same train/val/test split | {comparison['experiment_parity']['same_split_column']} |",
            f"| Same label encoding (train-only, 955 classes) | yes |",
            f"| Same evaluation protocol | {comparison['experiment_parity']['same_evaluation_protocol']} |",
            "",
            "**Primary comparison slices:** `seen_class / pair_type_dedup` and `frequent_ge_20 / pair_type_dedup`.",
            "",
            "Row-level metrics are reported separately in saved per-model protocol JSON files.",
            "",
            "---",
            "",
        ]
    )

    for section_idx, (split_title, split_name) in enumerate([("Validation", "val"), ("Test", "test")], start=1):
        lines.append(f"## 3.{section_idx}. {split_title} metrics (pair_type_dedup)")
        lines.append("")
        for slice_name, level in [
            ("seen_class", "pair_type_dedup_level"),
            ("frequent_ge_20", "pair_type_dedup_level"),
        ]:
            slice_key = f"{slice_name}/{level.replace('_level', '')}"
            rows = comparison["splits"][split_name][slice_key]
            n_info = next(iter(rows.values()))
            lines.append(f"### {split_title} — `{slice_name}` / pair_type_dedup")
            lines.append("")
            lines.append(
                f"n = {n_info.get('n_samples')} pair-types, {n_info.get('n_classes')} classes (same across models)."
            )
            lines.append("")
            header = ["Metric", "Logistic Regression", "Static GAT", "Molecular GNN", "Best model(s)"]
            lines.append(_table_row(header))
            lines.append(_table_row(["---"] * len(header)))
            for metric in METRIC_KEYS:
                values = {k: rows[k].get(metric) for k in MODEL_SPECS}
                best = comparison["best_by_metric"][f"{split_name}/{slice_key}/{metric}"]["best_models"]
                best_names = ", ".join(MODEL_SPECS[k]["display_name"] for k in best)
                lines.append(
                    _table_row(
                        [
                            metric,
                            format_pct(values["logistic_regression"]),
                            format_pct(values["static_gat"]),
                            format_pct(values["molecular_gnn"]),
                            best_names,
                        ]
                    )
                )
            lines.append("")

            lines.append(f"**Relative change vs Logistic Regression ({split_title}, `{slice_name}`):**")
            lines.append("")
            lines.append(_table_row(["Metric", "Static GAT", "Molecular GNN"]))
            lines.append(_table_row(["---", "---", "---"]))
            for metric in METRIC_KEYS:
                rel = comparison["relative_to_logistic_regression"][f"{split_name}/{slice_key}/{metric}"]
                lines.append(
                    _table_row(
                        [
                            metric,
                            format_relative(rel.get("static_gat")),
                            format_relative(rel.get("molecular_gnn")),
                        ]
                    )
                )
            lines.append("")

    lines.extend(
        [
            "---",
            "",
            "## 4. Interpretation",
            "",
            "### Did Static GAT improve over Logistic Regression?",
            "",
            "On **primary test slices** (pair_type_dedup), Static GAT and Logistic Regression",
            "perform at the same order of magnitude. Differences are small fractions of a",
            "percentage point and **no statistical significance testing was performed**.",
            "",
            "### Did Molecular GNN improve over Logistic Regression and Static GAT?",
            "",
            "Molecular GNN shows mixed results: modest gains on some top-k metrics (especially",
            "validation) but not uniformly on test primary slices. Improvements are **not",
            "large enough to claim meaningful performance gains** without confidence intervals",
            "or significance tests.",
            "",
            "### Is added model complexity justified?",
            "",
            "**Not strongly justified by current test metrics alone.** All three models operate",
            "near the random baseline for top-1 accuracy (~0.1% for 955 classes). Graph models",
            "add training cost and implementation complexity without clear test-set separation.",
            "",
            "### Limitations of the 955-class task",
            "",
            "- **955 train-fit classes** from only **145 unique drug pairs** and **26,597 rows**",
            "- **62% of train types** have fewer than 20 examples; only **64 types** have ≥50",
            "- **7 types** never appear in train (unlearnable at val/test)",
            "- **Pair-level split** leaves only **21 val / 23 test pairs** — high metric variance",
            "- Repeated `(pair_key, type)` admissions inflate row-level counts",
            "",
            "### Is 955-class prediction suitable as the final research task?",
            "",
            "**Not as the sole headline task.** It is useful as an exploratory benchmark, but",
            "primary research conclusions should use **top-k metrics**, **frequent-class slices**,",
            "and/or a **reformulated target** (e.g. coarse type groups, pair-level multi-label).",
            "",
            "---",
            "",
            "## 5. Recommendation for next research stage",
            "",
            "1. **Do not prioritize further model complexity** (e.g. Temporal GNN) until the",
            "   target formulation is refined or more pair/type coverage is available.",
            "2. **Adopt a frequent-class or top-k primary metric** for model selection reporting.",
            "3. **Compare models on row-level vs pair_type_dedup** consistently in all write-ups.",
            "4. Consider **pair-level multi-label** or **type grouping** as the next task definition.",
            "5. If continuing neural models, focus on **data/regime limitations** rather than",
            "   architecture depth given the small pair holdout.",
            "",
            "---",
            "",
            "*Generated by `python -m src.evaluation.run_baseline_comparison`. Machine-readable:",
            "`results/metrics/baseline_comparison.json`.*",
            "",
        ]
    )
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Build multiclass baseline comparison report")
    parser.add_argument("--output-json", default=str(OUTPUT_JSON))
    parser.add_argument("--output-md", default=str(OUTPUT_MD))
    args = parser.parse_args(argv)

    comparison = build_baseline_comparison()
    json_path = Path(args.output_json)
    md_path = Path(args.output_md)
    json_path.parent.mkdir(parents=True, exist_ok=True)
    json_path.write_text(json.dumps(comparison, indent=2, default=str) + "\n", encoding="utf-8")
    md_path.write_text(render_markdown(comparison), encoding="utf-8")
    print(f"Wrote {json_path}")
    print(f"Wrote {md_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
